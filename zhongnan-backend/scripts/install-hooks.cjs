#!/usr/bin/env node
/**
 * v2.479 本地 Git 钩子安装器（幂等）
 *
 * 用法：
 *   node scripts/install-hooks.cjs                 # 装到当前仓库的 .git/hooks
 *   node scripts/install-hooks.cjs --dir <gitDir>  # 装到指定目录（测试用）
 *   node scripts/install-hooks.cjs --force         # 覆盖非本安装器写的外来钩子（先备份）
 *
 * 为什么存在：`scope-guard`（防跑偏 + 版本四处一致）此前只能靠人记得敲，
 * 「忘记敲」正是跑偏改动/半截版本被推上远端的主要泄漏路径。钩子目录按纪律不入库，
 * 所以把「安装」固化成一条命令：一次安装，之后每次 commit / push 都自动过闸。
 *
 * 安全边界：
 *   - 只接管带 marker 的钩子；别人的钩子必须显式 --force，且先备份成 <stage>.bak.<ts>；
 *   - 钩子内只跑 scope-guard（毫秒级），不跑全量测试——闸门一旦变慢就会被绕过。
 */
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const MARKER = 'zn-hooks:managed';
/**
 * v2.484：从「只在 push 前拦截」前移到「commit 前也拦截」。
 * 事实依据：跑偏/版本半截进入本地历史的成本高于进入暂存区——一旦 commit，后续
 * 要 reset/rebase 才能清掉，且旧 commit 里可能残留截图。两道闸门都只跑毫秒级
 * scope-guard，不做全量测试，避免因慢而被绕过。
 */
function makeHook(stage) {
  const label = stage === 'pre-commit' ? '提交' : '推送';
  return [
    '#!/bin/sh',
    `# ${MARKER} — generated by zhongnan-backend/scripts/install-hooks.cjs; edits will be overwritten`,
    `# ${label}前过「防跑偏 + 版本四处一致」闸门：失败即中止 ${stage.replace('pre-', '')}（修复后重试即可）。`,
    'root=$(git rev-parse --show-toplevel 2>/dev/null) || exit 0',
    'cd "$root" || exit 0',
    'node "$root/zhongnan-backend/scripts/scope-guard.cjs" || {',
    '  echo "" >&2',
    `  echo "${stage} 已拦截：改动跑偏或版本不一致（详见上方输出）。修复后再${label}。" >&2`,
    '  exit 1',
    '}',
    '',
  ].join('\n');
}
const HOOKS = ['pre-commit', 'pre-push'].map((stage) => ({ stage, src: makeHook(stage) }));

function arg(name, def) {
  const i = process.argv.indexOf(name);
  if (i < 0) return def;
  const next = process.argv[i + 1];
  return next && !next.startsWith('--') ? next : true;
}

function resolveGitDir() {
  const given = arg('--dir', '');
  if (typeof given === 'string' && given) return path.resolve(given);
  const r = spawnSync('git', ['rev-parse', '--git-dir'], { encoding: 'utf8' });
  if (r.status !== 0) {
    console.error('✗ 当前目录不是 Git 仓库（也可用 --dir 指定）');
    process.exit(1);
  }
  return path.resolve(r.stdout.trim());
}

function main() {
  const force = !!arg('--force', false);
  const gitDir = resolveGitDir();
  const hooksDir = path.join(gitDir, 'hooks');
  fs.mkdirSync(hooksDir, { recursive: true });

  for (const { stage, src } of HOOKS) {
    const hookPath = path.join(hooksDir, stage);
    if (fs.existsSync(hookPath)) {
      const cur = fs.readFileSync(hookPath, 'utf8');
      if (cur === src) {
        console.log(`✓ ${stage} 已是最新，无需改动：` + hookPath);
        continue;
      }
      if (!cur.includes(MARKER)) {
        if (!force) {
          console.error(`✗ 已存在非本安装器创建的 ${stage}：` + hookPath);
          console.error('  确认要接管请加 --force（会先备份为 ' + stage + '.bak.<时间戳>）');
          process.exit(1);
        }
        const bak = hookPath + '.bak.' + Date.now();
        fs.copyFileSync(hookPath, bak);
        console.log('• 已备份外来钩子：' + bak);
      }
    }
    fs.writeFileSync(hookPath, src, { mode: 0o755 });
    fs.chmodSync(hookPath, 0o755);
    console.log(`✓ 已安装 ${stage}（${stage === 'pre-commit' ? '提交' : '推送'}前自动跑 scope-guard）：` + hookPath);
  }
}

main();
