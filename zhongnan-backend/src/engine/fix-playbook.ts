/** 规则别名：部分入口规则名与引擎键不同名时映射到同一条兵法 */
const ALIASES: Record<string, string> = {
  actionEchoDialogue: 'actionEcho',
  misunderstandingDrag: 'misunderstanding',
  softSceneEnding: 'sceneSoftEnding',
  antiCliché: 'cliche',
};

/**
 * 取某条规则的专科兵法。未收录返回 null（调用方退回通用提示，不阻断）。
 */
export function getFixPlaybook(rule: string, lang: 'zh' | 'en' = 'zh'): FixPlaybook | null {
  const key = String(rule || '').trim();
  const hit = ALIASES[key] || key;
  const table = lang === 'en' ? EN : ZH;
  const e = table[hit];
  if (!e) return null;
  return { cliche: e[0], moves: e[1].filter(Boolean), win: e[2] };
}

/**
 * 构造注入润色师 prompt 的兵法块；无收录规则返回空串（调用方直接省略）。
 */
export function buildPlaybookBlock(rule: string, lang: 'zh' | 'en' = 'zh'): string {
  const p = getFixPlaybook(rule, lang);
  if (!p) return '';
  if (lang === 'en') {
    return [
      `Specialty playbook — how this exact pathology looks: ${p.cliche}`,
      `Rewrite moves: ${p.moves.map((m, i) => `${i + 1}) ${m}`).join(' ')}`,
      `Acceptance test: ${p.win}`,
    ].join('\n');
  }
  return [
    `【专科改写兵法】病灶识别：${p.cliche}`,
    `改写手法：${p.moves.map((m, i) => `${['①', '②', '③'][i] || '·'}${m}`).join(' ')}`,
    `改完自检：${p.win}`,
  ].join('\n');
}

