/**
 * fix-playbook.ts —— 诊断→一键优化的「专科改写兵法库」（c220）
 * ------------------------------------------------------------------
 * 病象：buildFixPrompt 此前对 130+ 种病症引擎只传一句通用 advice，润色师拿到的是
 * 「请解决：台词AI味重」这种正确的废话——没有病灶识别特征、没有可执行手法、没有
 * 验收标准。同一个模型，有没有专科打法，改稿质量相差一个档：通用提示下模型倾向
 * 「换几个词」，专科兵法要求动结构（删整场、改主动选择、埋前置物证）。
 *
 * 本模块：rule（引擎键，与 qcReport 键 / QC 卡 data-rule 同源）→ 三要素
 *  - cliche：病灶长什么样（帮模型在原稿里精准定位，不误伤无关段落）
 *  - moves：2-3 个可执行改写手法（具体到删/换/补，不是「加强刻画」式空话）
 *  - win：改完必须达到的验收标准（可自检，防模型换汤不换药）
 *
 * 纪律：
 *  - 纯数据纯函数、零依赖、可单测；未收录规则返回 null，调用方退回通用提示（不硬编）。
 *  - 每条 ≤140 汉字，控制润色师 prompt token（付费链路）。
 *  - 只覆盖单集可解决的病症；跨集台账（ledger 30 键）改写语义涉及前序集，不在此库。
 */

export interface FixPlaybook {
  /** 病灶识别特征：这个病在稿子里具体长什么样 */
  cliche: string;
  /** 可执行改写手法（删/换/补/重构），每条一个具体动作 */
  moves: string[];
  /** 验收标准：改完这处必须满足什么 */
  win: string;
}

type Entry = [cliche: string, moves: string[], win: string];

