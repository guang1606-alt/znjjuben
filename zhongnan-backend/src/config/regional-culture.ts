const BY_ID = new Map(REGION_CARDS.map((c) => [c.id, c]));
const NAME_INDEX = new Map<string, RegionCard>();
REGION_CARDS.forEach((c) => { NAME_INDEX.set(c.name, c); c.aliases.forEach((a) => NAME_INDEX.set(a, c)); });

export function listRegions(): RegionCard[] { return REGION_CARDS.slice(); }
export function getRegionCard(idOrName?: string): RegionCard | undefined {
  if (!idOrName) return undefined;
  const key = String(idOrName).trim();
  return BY_ID.get(key) ?? NAME_INDEX.get(key) ?? REGION_CARDS.find((c) => key.includes(c.name) || c.aliases.some((a) => key.includes(a)));
}
/** 从一段自由文本（主页简介/IP 归属/聊天）推断最可能的地域卡 */
export function matchRegion(text?: string): RegionCard | undefined {
  if (!text) return undefined;
  return getRegionCard(text);
}
/** 生成给人设/撰写岗的“地域贴合”指令行；未知地域安全返回空串（不硬凑、不四不像） */
export function regionalBrief(idOrName?: string): string {
  const c = getRegionCard(idOrName);
  if (!c) return '';
  return [
    `【地域贴合·${c.name}】人物性格：${c.traits.join('、')}；`,
    `语言：${c.speechStyle}（可少量点染语气词：${c.particles.slice(0, 4).join('/')}，以全国观众听得懂为度）；`,
    `生活细节可借：${c.lifeDetails.slice(0, 4).join('、')}；典型场景：${c.scenes.slice(0, 3).join('、')}；`,
    `人情：${c.relations.join('；')}；禁忌：${c.taboos.join('；')}。`,
  ].join('');
}
